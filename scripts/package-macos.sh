#!/bin/bash
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
: "${NOTARY_PROFILE:?Set NOTARY_PROFILE to an existing local notarytool keychain profile}"
app="$root/macos/out/Pixel Volume.app"
version="$(/usr/libexec/PlistBuddy -c 'Print CFBundleShortVersionString' "$app/Contents/Info.plist")"
mkdir -p "$root/artifacts"
stage="$(mktemp -d "$root/artifacts/macos-package.XXXXXX")"
ditto -c -k --keepParent "$app" "$stage/application.zip"
xcrun notarytool submit "$stage/application.zip" --keychain-profile "$NOTARY_PROFILE" --wait --output-format json > "$stage/app-notary.json"
python3 -c 'import json,sys; assert json.load(open(sys.argv[1]))["status"] == "Accepted"' "$stage/app-notary.json"
xcrun stapler staple "$app"
xcrun stapler validate "$app"
mkdir "$stage/image"
ditto "$app" "$stage/image/Pixel Volume.app"
ln -s /Applications "$stage/image/Applications"
dmg="$root/artifacts/PixelVolume-$version-macOS-Universal.dmg"
test ! -e "$dmg" || { echo 'Refusing to overwrite an existing distribution artifact' >&2; exit 1; }
hdiutil create -volname "像素音量 $version" -srcfolder "$stage/image" -format UDZO "$dmg"
identity="$(security find-identity -v -p codesigning | awk '/Developer ID Application:/{print $2}')"
[[ "$identity" =~ ^[0-9A-F]{40}$ ]] || { echo 'Expected one Developer ID signing identity' >&2; exit 1; }
codesign --force --timestamp --sign "$identity" "$dmg"
xcrun notarytool submit "$dmg" --keychain-profile "$NOTARY_PROFILE" --wait --output-format json > "$stage/dmg-notary.json"
python3 -c 'import json,sys; assert json.load(open(sys.argv[1]))["status"] == "Accepted"' "$stage/dmg-notary.json"
xcrun stapler staple "$dmg"
xcrun stapler validate "$dmg"
codesign --verify --deep --strict --all-architectures "$app"
codesign --verify --strict "$dmg"
hdiutil verify "$dmg"
sparkle="$(bash "$root/scripts/fetch-sparkle.sh")"
"$sparkle/bin/sign_update" --account pixel-volume-release -p "$dmg" > "$dmg.ed25519"
"$sparkle/bin/sign_update" --account pixel-volume-release --verify "$dmg" "$(cat "$dmg.ed25519")"
shasum -a 256 "$dmg"
